#define COUNT ((int)(sizeof archive / sizeof archive[0]))

static void decode(const struct message *m, char *out) {
    for (int i = 0; i < m->len; i++) out[i] = (char)(m->text[i] ^ m->key);
    out[m->len] = 0;
}

/* FNV-1a, so the unlock word itself is not stored anywhere in the program. */
static unsigned int word_hash(const char *s) {
    unsigned int h = 0x811C9DC5u;
    while (*s) {
        h ^= (unsigned char)*s++;
        h *= 0x01000193u;
    }
    return h;
}

int main(void) {
    char line[64];
    char text[64];

    printf("Keeper's log: %d messages. Enter a number to read one, or the unlock word: ", COUNT);
    if (!fgets(line, sizeof line, stdin)) return 1;
    line[strcspn(line, "\r\n")] = 0;

    if (line[0] && strspn(line, "0123456789") == strlen(line)) {
        int n = atoi(line);
        if (n < 1 || n > COUNT) {
            puts("No such message.");
            return 1;
        }
        const struct message *m = &archive[n - 1];
        if (m->sealed) {
            printf("Message %d is sealed.\n", n);
            return 1;
        }
        decode(m, text);
        printf("Message %d: %s\n", n, text);
        return 0;
    }

    if (word_hash(line) == 0xAC9CA843u) {
        puts("Archive unlocked. Welcome back, keeper.");
        return 0;
    }
    puts("Wrong unlock word.");
    return 1;
}
